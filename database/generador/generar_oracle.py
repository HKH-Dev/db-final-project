"""Traduce database/01_esquema.sql (MariaDB) a DDL de Oracle para importarlo en Oracle SQL Developer Data Modeler.

Salida: docs/modelo-datos-oracle.sql. Mismas 31 tablas, columnas, llaves, CHECK, indices y comentarios.
Uso: python3 generar_oracle.py
"""
import re
from pathlib import Path
from diccionario import TABLAS, C

raiz = Path(__file__).resolve().parent.parent.parent
sql = (raiz / "database" / "01_esquema.sql").read_text(encoding="utf-8")


def tipo_oracle(t):
    t = t.upper()
    m = re.match(r"(\w+)(?:\((\d+)(?:,(\d+))?\))?", t)
    base, p, s = m.group(1), m.group(2), m.group(3)
    if base == "INT":
        return "NUMBER(10)"
    if base == "TINYINT":
        return "NUMBER(1)"
    if base == "VARCHAR":
        return f"VARCHAR2({p})"
    if base == "CHAR":
        return f"CHAR({p})"
    if base == "DECIMAL":
        return f"NUMBER({p},{s})" if s and s != "0" else f"NUMBER({p})"
    if base == "DATE":
        return "DATE"
    if base == "DATETIME":
        return "TIMESTAMP"
    raise ValueError(t)


def check_oracle(expr):
    expr = re.sub(r"(\w+) REGEXP '([^']+)'", r"REGEXP_LIKE(\1, '\2')", expr)
    if "<>" in expr and "IS NULL" in expr:  # pago: de un pedido o de una suscripcion, no de ambos
        return "(id_pedido IS NULL AND id_suscripcion IS NOT NULL) OR (id_pedido IS NOT NULL AND id_suscripcion IS NULL)"
    return expr


def nombre30(n):
    return n.upper()[:30]


tablas = []
for m in re.finditer(r"CREATE TABLE (\w+) \((.*?)\n\) ENGINE", sql, re.S):
    nombre, cuerpo = m.group(1), m.group(2)
    cols, cons = [], []
    for linea in cuerpo.splitlines():
        linea = re.sub(r"\s+--.*$", "", linea).strip().rstrip(",")
        if not linea:
            continue
        if linea.startswith("CONSTRAINT"):
            cons.append(linea)
            continue
        cm = re.match(r"(\w+)\s+(\w+(?:\([\d,]+\))?)\s*(.*)", linea)
        col, tipo, resto = cm.groups()
        resto = re.sub(r"COMMENT '.*'$", "", resto).strip()
        cols.append(dict(col=col, tipo=tipo, nulo="NOT NULL" not in resto, auto="AUTO_INCREMENT" in resto,
                         defecto=(re.search(r"DEFAULT (\S+)", resto) or [None, None])[1]))
    tablas.append((nombre, cols, cons))
indices = re.findall(r"CREATE INDEX (\w+) ON (\w+) \(([^)]+)\);", sql)

o = []
o.append("""-- =====================================================================================
--  FrutiMarket BD · Modelo de datos para Oracle SQL Developer Data Modeler (Oracle 12c+)
--  Universidad del Quindío · Bases de Datos 2026-2
--
--  GENERADO desde database/01_esquema.sql (MariaDB) por database/generador/generar_oracle.py.
--  Es el mismo modelo que usa la aplicación: 31 tablas (30 entidades fuertes y la entidad
--  débil DETALLE_PEDIDO), con sus columnas, llaves, restricciones CHECK, índices y comentarios.
--  Equivalencias de tipos: INT -> NUMBER(10), DECIMAL(p,s) -> NUMBER(p,s), VARCHAR -> VARCHAR2,
--  TINYINT(1) -> NUMBER(1) con CHECK (0,1), DATETIME -> TIMESTAMP, AUTO_INCREMENT -> IDENTITY.
--
--  Uso en Data Modeler:  File > Import > DDL File > este archivo > Oracle Database 12c
--  (crea el modelo relacional; Design > Engineer to Logical Model genera el modelo lógico).
-- =====================================================================================
""")
for nombre, cols, cons in tablas:
    T = nombre.upper()
    o.append(f"\nCREATE TABLE {T} (")
    lineas = []
    for c in cols:
        ln = f"    {c['col']:<26}{tipo_oracle(c['tipo']):<14}"
        if c["auto"]:
            ln += " GENERATED BY DEFAULT ON NULL AS IDENTITY"
        d = c["defecto"]
        if d:
            d = "SYSTIMESTAMP" if d == "CURRENT_TIMESTAMP" else d
            ln += f" DEFAULT {d}"
        ln += " NOT NULL" if not c["nulo"] else ""
        lineas.append(ln.rstrip())
    for k in cons:
        km = re.match(r"CONSTRAINT (\w+) (.*)", k)
        cn, defin = nombre30(km.group(1)), km.group(2)
        if defin.startswith("CHECK"):
            expr = re.match(r"CHECK \((.*)\)$", defin).group(1)
            defin = f"CHECK ({check_oracle(expr)})"
        if defin.startswith("FOREIGN KEY"):
            defin = re.sub(r"REFERENCES (\w+)", lambda x: "REFERENCES " + x.group(1).upper(), defin)
        lineas.append(f"    CONSTRAINT {cn} {defin}")
    for c in cols:
        if c["tipo"].upper().startswith("TINYINT"):
            lineas.append(f"    CONSTRAINT {nombre30('ck_' + nombre[:10] + '_' + c['col'])} CHECK ({c['col']} IN (0, 1))")
    o.append(",\n".join(lineas))
    o.append(");")
    for ix, tb, cl in indices:
        if tb == nombre:
            o.append(f"CREATE INDEX {nombre30(ix)} ON {T} ({cl});")
    o.append(f"COMMENT ON TABLE {T} IS '{TABLAS[nombre]}';")
    for c in cols:
        o.append(f"COMMENT ON COLUMN {T}.{c['col']} IS '{C[nombre][c['col']].replace(chr(39), chr(39) * 2)}';")

destino = raiz / "docs" / "modelo-datos-oracle.sql"
destino.write_text("\n".join(o) + "\n", encoding="utf-8")
print(destino, len(tablas), "tablas")

# catalogos: INSERT de una fila (Oracle no admite VALUES de varias filas) tomados de 03_datos.sql
datos = (raiz / "database" / "03_datos.sql").read_text(encoding="utf-8")
CATALOGOS = ["departamento", "cargo", "tipo_cliente", "periodicidad", "tipo_metodo_pago", "tipo_notificacion",
             "estado_suscripcion", "estado_pedido", "estado_pago", "estado_despacho", "rol", "categoria"]
cat = ["-- =====================================================================================",
       "--  FrutiMarket BD · Datos de los catalogos para Oracle (ejecutar despues de modelo-datos-oracle.sql)",
       "--  GENERADO desde database/03_datos.sql por database/generador/generar_oracle.py",
       "-- =====================================================================================", ""]
for t in CATALOGOS:
    m = re.search(rf"INSERT INTO {t} \(([^)]*)\) VALUES\n(.*?);\n", datos, re.S)
    cols = m.group(1)
    for fila in m.group(2).split("),\n("):
        fila = fila.strip().lstrip("(").rstrip(")")
        cat.append(f"INSERT INTO {t.upper()} ({cols}) VALUES ({fila});")
    cat.append("")
cat.append("COMMIT;")
(raiz / "docs" / "catalogos-oracle.sql").write_text("\n".join(cat) + "\n", encoding="utf-8")
print("catalogos-oracle.sql", sum(1 for x in cat if x.startswith("INSERT")), "filas")
